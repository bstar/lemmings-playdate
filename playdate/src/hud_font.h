static const uint8_t* hud_glyph_for(char character) {
    if (character >= '0' && character <= '9')
        return hud_digit_glyphs[(unsigned)(character - '0')];
    if (character >= 'A' && character <= 'Z')
        return hud_letter_glyphs[(unsigned)(character - 'A')];
    return NULL;
}

